"""Generate the colour palettes from T3 Code's built-in themes.

T3 Code (the desktop app) ships six themes, each with a light and a dark
variant. This reads them out of an installed copy's server.asar and writes:

  src/palettes.css         dashboard tokens per palette and light/dark
  src/widget-palettes.css  widget and strip tokens per palette and light/dark
  src/palettes.js          id, label and swatch colours for the picker

Run from the repository root:
  python tools/gen_palettes.py [path/to/server.asar]
"""
import json
import os
import re
import sys

DEFAULT_ASAR = os.path.join(
    os.environ.get("LOCALAPPDATA", ""), "Programs", "t3code", "resources", "server.asar"
)
PAIR = re.compile(r"(\w+):`([^`]*)`")
NAMED = ("t3-chat", "grove", "ocean", "ember", "iris")


def object_at(text, brace):
    depth = 0
    for i in range(brace, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return dict(PAIR.findall(text[brace:i + 1]))
    raise ValueError("unbalanced object literal")


def read_themes(asar):
    data = open(asar, "rb").read().decode("utf-8", "replace")
    themes = []
    # The default theme is two flat objects, told apart by their canvas.
    modes = {}
    for mode, canvas in (("light", "#fcfcfc"), ("dark", "#0a0a0a")):
        at = data.find("canvas:`%s`,chrome" % canvas)
        if at < 0:
            raise SystemExit("T3 Code default %s theme not found" % mode)
        modes[mode] = object_at(data, data.rfind("={", 0, at) + 1)
    themes.append({"id": "t3-code", "label": "T3 Code", **modes})
    for tid in NAMED:
        at = data.find("id:`%s`,label:" % tid)
        if at < 0:
            raise SystemExit("T3 Code theme %s not found" % tid)
        label = re.match(r"id:`[^`]+`,label:`([^`]+)`", data[at:at + 80]).group(1)
        colors = data.find("colors:{", at)
        dark = data.find("variants:{dark:{", colors)
        themes.append({
            "id": tid,
            "label": label,
            "light": object_at(data, colors + len("colors:")),
            "dark": object_at(data, dark + len("variants:{dark:")),
        })
    return themes


# The meters, figures and pace mark use `focus`, not `accent`. They are the
# same colour in every theme but T3 Chat dark, whose accent is a deep fill for
# buttons and is unreadable as text on its dark canvas; its focus is the
# brighter shade T3 itself draws on that canvas.


def dashboard_tokens(c):
    return {
        "--panel": c["canvas"],
        "--title": c["text"],
        "--section": c["text"],
        "--label": c["textMuted"],
        "--value": c["text"],
        "--accent": c["focus"],
        "--loading": c["textMuted"],
        "--track": c["border"],
        "--rule": c["border"],
        "--chip": c["muted"],
        "--hover": c["accentSurface"],
        "--surface": c["surfaceRaised"],
        "--surface-strong": c["surfaceOverlay"],
        "--ok": c["focus"],
        "--warn": c["warning"],
        "--crit": c["error"],
    }


def widget_tokens(c):
    return {
        "--surface": "color-mix(in oklch, %s 94%%, transparent)" % c["surface"],
        "--surface-edge": c["border"],
        "--header": c["surfaceRaised"],
        "--title": c["text"],
        "--label": c["textMuted"],
        "--muted": c["mutedForeground"],
        "--rule": c["border"],
        "--hover": c["accentSurface"],
        "--ok": c["focus"],
        "--warning": c["warning"],
        "--critical": c["error"],
    }


HEADER = """/* Generated by tools/gen_palettes.py from T3 Code's built-in themes. Do not
   edit by hand: rerun the script. No data-palette attribute means the
   original palette in %s. */
"""


def css(themes, tokens, base):
    out = [HEADER % base]
    for theme in themes:
        for mode in ("light", "dark"):
            selector = ':root[data-palette="%s"]' % theme["id"]
            if mode == "dark":
                selector += '[data-theme="dark"]'
            body = "\n".join("  %s: %s;" % kv for kv in tokens(theme[mode]).items())
            out.append("%s {\n%s\n}\n" % (selector, body))
    return "\n".join(out)


def main():
    asar = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_ASAR
    themes = read_themes(asar)
    with open("src/palettes.css", "w", encoding="utf-8", newline="\n") as f:
        f.write(css(themes, dashboard_tokens, "styles.css"))
    with open("src/widget-palettes.css", "w", encoding="utf-8", newline="\n") as f:
        f.write(css(themes, widget_tokens, "widget.css"))
    swatches = [
        {
            "id": t["id"],
            "label": t["label"],
            "light": {"canvas": t["light"]["canvas"], "accent": t["light"]["focus"]},
            "dark": {"canvas": t["dark"]["canvas"], "accent": t["dark"]["focus"]},
        }
        for t in themes
    ]
    with open("src/palettes.js", "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_palettes.py from T3 Code's built-in themes.\n")
        f.write("export const PALETTE_KEY = \"quota-deck-palette\";\n\n")
        f.write("export const PALETTES = ")
        f.write(json.dumps(swatches, ensure_ascii=False, indent=2))
        f.write(";\n")
    print("wrote %d palettes" % len(themes))


if __name__ == "__main__":
    main()
